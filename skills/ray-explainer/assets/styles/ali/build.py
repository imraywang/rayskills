def on_board(t): return any(a <= t < b for a, b in BOARDS)

def caps():
    out = []
    for i, (s, e, t) in enumerate(CAPS, 1):
        if round(s, 2) in HIDE: continue
        m = "b" if on_board(s + 0.01) else "a"
        out.append(f'      <div id="cap-{i:03d}" class="cap clip cap-{m}" data-start="{s:.2f}" data-duration="{e - s:.2f}" data-track-index="9"><span>{t.replace("**", "")}</span></div>')
    return "\n".join(out)

def sfx():
    return "\n".join(f'      <audio id="sfx-{i:03d}" src="assets/sfx/pop.wav" data-start="{t:.2f}" data-duration="0.12" data-track-index="8" data-volume="0.16"></audio>'
                     for i, t in enumerate(POPS, 1))

def cam():
    rows = []
    for s, e, sc, y, d in CAM:
        rows.append(f"      tl.set(A, {{ scale: {sc}, x: 0, y: {y} }}, {s});")
        rows.append(f'      tl.to(A, {{ scale: {d}, duration: {e - s:.2f}, ease: "none" }}, {s});')
    return "\n".join(rows)

def pcard():
    rows = ['      tl.set("#pcard", { opacity: 0 }, 0);']
    merged = []
    for a, b in BOARDS:
        if merged and abs(merged[-1][1] - a) < 0.01: merged[-1][1] = b
        else: merged.append([a, b])
    for a, b in merged:
        rows.append(f'      tl.fromTo("#pcard", {{ opacity: 0, y: 16 }}, {{ opacity: 1, y: 0, duration: 0.45, ease: "power3.out" }}, {a + 0.15:.2f});')
        rows.append(f'      tl.set("#pcard", {{ opacity: 0 }}, {b});')
    return "\n".join(rows)

