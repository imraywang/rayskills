html = (html.replace("/*DUR*/", str(DUR)).replace("<!--CAPTIONS-->", caps()).replace("<!--SFX-->", sfx())
        .replace("//CAM", cam()).replace("//PCARD", pcard()))
open("index.html", "w", encoding="utf-8").write(html)

